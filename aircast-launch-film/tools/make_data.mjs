// Packs the frozen AirCast snapshot and the measured page layout into
// assets/js/aircast-data.js, which the film loads as a local script (renders never fetch).
// Also fits the map projection: the site's map is Web Mercator, so page x is linear in
// longitude and page y is linear in mercator(latitude). The fit uses all 30 station dots
// measured on the live page (assets/plates/layout.json).
//
// Run from the film folder: node tools/make_data.mjs

import { readFileSync, writeFileSync } from 'node:fs';

const air = JSON.parse(readFileSync('assets/data/air-and-wind.json', 'utf8'));
const history = JSON.parse(readFileSync('assets/data/history-grensas.json', 'utf8'));
const layout = JSON.parse(readFileSync('assets/plates/layout.json', 'utf8'));

const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));

// Least-squares line through (u, v) pairs: v = a*u + b.
function fit(pairs) {
  const n = pairs.length;
  const su = pairs.reduce((s, [u]) => s + u, 0);
  const sv = pairs.reduce((s, [, v]) => s + v, 0);
  const suu = pairs.reduce((s, [u]) => s + u * u, 0);
  const suv = pairs.reduce((s, [u, v]) => s + u * v, 0);
  const a = (n * suv - su * sv) / (n * suu - su * su);
  return { a, b: (sv - a * su) / n };
}

const points = layout.markers.map((m) => {
  const name = m.title.split(':')[0];
  const s = air.stations.find((st) => st.name === name);
  if (!s) throw new Error(`No station for marker ${m.title}`);
  return { name, lat: s.lat, lon: s.lon, x: m.cx, y: m.cy };
});
const fx = fit(points.map((p) => [p.lon, p.x]));
const fy = fit(points.map((p) => [mercY(p.lat), p.y]));
const worst = Math.max(...points.map((p) => Math.hypot(fx.a * p.lon + fx.b - p.x, fy.a * mercY(p.lat) + fy.b - p.y)));
console.log(`projection fitted on ${points.length} dots, worst error ${worst.toFixed(2)} px`);

const data = {
  takenAt: air.fetchedAt,
  projection: { ax: fx.a, bx: fx.b, ay: fy.a, by: fy.b }, // page px (1x) from lon / mercator(lat)
  layout,
  stations: air.stations.map((s) => ({ id: s.id, name: s.name, lat: s.lat, lon: s.lon, level: s.level })),
  wind: air.wind, // { lat, lon, speed, from } for every weather station
  grensas: air.stations.find((s) => s.id === 'STA-IS0005A'),
  no2Day: history.readings.find((r) => r.code === 'NO2'),
};

writeFileSync('assets/js/aircast-data.js', `// Generated by tools/make_data.mjs from the ${air.fetchedAt} snapshot. Do not edit by hand.\nwindow.AIRCAST = ${JSON.stringify(data)};\n`);
console.log('wrote assets/js/aircast-data.js');
